import { chromium, expect } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
const root = 'apps/msd/artifacts/cms-articles';
const base = process.env.MSD_BROWSER_URL || 'http://localhost:4200';
const menu = JSON.parse(await readFile('packages/shared-menu/src/msd-menu.json', 'utf8')).filter(node => node.id === 'cms');
const id = 'f0f0f0f0-0000-4000-8000-000000000010';
const categoryId = 'c0c0c0c0-0000-4000-8000-000000000099';
const article = { id, title: 'Routing regression article', slug: 'routing-regression', excerpt: 'Test article', categoryId, category: { id: categoryId, name: 'Wellness' }, author: 'Test Author', readMinutes: 2, body: [{ type: 'paragraph', text: 'Test body' }], tags: [], status: 'DRAFT', publishedAt: null, createdAt: '2026-10-17T00:00:00Z', updatedAt: '2026-10-17T00:00:00Z', mediaImages: [] };
let permissions = ['cms.blog.pages:view','cms.blog.pages:create','cms.blog.pages:edit','cms.blog.pages:delete','cms.blog.articles:view','cms.blog.articles:create','cms.blog.articles:edit','cms.blog.articles:delete','cms.blog-category:view'];
const user = { id: 'test-admin', name: 'Routing Test', email: 'routing@example.test', status: 'active' };
const envelope = (data, meta) => ({ data, error: null, ...(meta ? { meta } : {}) });
const checks = [], requests = [], errors = [];
const record = checks.push.bind(checks);
checks.push = (...messages) => { console.log(...messages); return record(...messages); };
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
// Test identity exists ONLY at the intercepted network boundary; no signed token or real login is used.
const b64 = data => Buffer.from(JSON.stringify(data)).toString('base64url');
await context.addInitScript(token => localStorage.setItem('msd_auth_token', token), `${b64({ alg: 'none' })}.${b64({ sub: 'test-admin', roles: ['admin'], app: 'msd', exp: Math.floor(Date.now()/1000)+3600 })}.test`);
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
await page.route('**/api/v1/**', async route => {
  const request = route.request(), url = new URL(request.url()), path = url.pathname.replace('/api/v1', '');
  requests.push({ method: request.method(), path: path + url.search });
  if (path === '/rbac/bootstrap') return route.fulfill({ json: envelope({ user, roles: [{ id: 'role-admin', key: 'admin', name: 'Admin', isSuperAdmin: false }], permissions, menu, dashboardWidgets: [] }) });
  if (path === '/rbac/users/me') return route.fulfill({ json: envelope({ ...user, roles: [] }) });
  if (path === '/blog-categories') return route.fulfill({ json: envelope([{ id: categoryId, name: 'Wellness', slug: 'wellness', isActive: true, sortOrder: 0 }], { total: 1 }) });
  if (/^\/blog-(articles|posts)$/.test(path)) return route.fulfill({ json: envelope([article], { total: 1, page: 1, pageSize: 10 }) });
  if (path === `/blog-articles/${id}` || path === `/blog-posts/${id}`) return route.fulfill({ json: envelope(article) });
  if (/^\/blog-(articles|posts)\//.test(path)) return route.fulfill({ status: 404, json: { data: null, error: { code: 'NOT_FOUND', message: 'Blog post not found.' } } });
  return route.fulfill({ json: envelope([], { total: 0, unreadCount: 0 }) });
});
try {
  await page.goto(`${base}/account/cms/blog/articles`, { waitUntil: 'domcontentloaded', timeout: 120000 });
  await expect(page.getByRole('heading', { name: 'Articles', exact: true })).toBeVisible({ timeout: 60000 });
  await expect(page.locator('sky-data-table').getByText(article.title, { exact: true })).toBeVisible();
  await expect(page.locator('.admin-sidebar a.active')).toHaveCount(1);
  await expect(page.locator('.admin-sidebar a.active')).toHaveText(/Articles/);
  await expect(page.getByText('Invalid route parameters', { exact: true })).toHaveCount(0);
  checks.push('direct Articles URL, populated DataTable, only Articles active, parents expanded');
  await page.screenshot({ path: `${root}/articles.png`, fullPage: true });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('heading', { name: 'Articles', exact: true })).toBeVisible();
  checks.push('browser refresh retains Articles listing');
  const nav = page.getByRole('navigation', { name: 'Console' });
  await nav.getByRole('link', { name: 'Pages', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Blog', exact: true })).toBeVisible();
  await expect(page.locator('.admin-sidebar a.active')).toHaveText(/Pages/);
  await nav.getByRole('link', { name: 'Articles', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Articles', exact: true })).toBeVisible();
  checks.push('sidebar Pages and Articles navigation');
  const table = page.locator('sky-data-table');
  await table.getByRole('button', { name: `View: ${article.title}`, exact: true }).click();
  await expect(page).toHaveURL(`${base}/account/cms/blog/articles/${id}`);
  await expect(page.getByRole('heading', { name: article.title, exact: true })).toBeVisible();
  await expect(page.locator('.admin-sidebar a.active')).toHaveText(/Articles/);
  await page.getByRole('link', { name: 'Back to Articles' }).click();
  await table.getByRole('button', { name: `Edit: ${article.title}`, exact: true }).click();
  await expect(page.locator('md-dialog[open]')).toContainText('Edit blog post');
  await expect(page.locator('md-dialog[open]').getByRole('textbox', { name: 'Title', exact: true })).toHaveValue(article.title);
  await page.locator('md-dialog[open]').getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'New blog post', exact: true }).click();
  await expect(page.locator('md-dialog[open]')).toContainText('New blog post');
  checks.push('article detail, Back to Articles, selected-row edit dialog and new article dialog');
  await page.locator('md-dialog[open]').getByRole('button', { name: 'Cancel', exact: true }).click();
  await table.evaluate(el => { window.cmsSearchEvents = []; el.addEventListener('sky-dt-params-change', event => window.cmsSearchEvents.push(event.detail)); });
  await table.getByRole('searchbox', { name: /Search by title/ }).fill('routing');
  console.log('search diagnostic', await table.evaluate(el => ({ events: window.cmsSearchEvents, search: el._search, fieldValue: el.shadowRoot.querySelector('md-outlined-text-field').value }))); 
  await expect.poll(() => requests.some(request => request.path.includes('/blog-articles?') && request.path.includes('search=routing'))).toBe(true);
  checks.push('article DataTable search reaches Articles list API');
  await page.goto(`${base}/account/cms/blog/${id}`);
  await expect(page.getByRole('heading', { name: article.title, exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Back to Blog' })).toBeVisible();
  checks.push('existing Pages detail route preserved');
  await page.goto(`${base}/account/cms/blog/articles/not-a-uuid`);
  await expect(page.getByRole('alert')).toHaveText('Blog post not found.');
  checks.push('invalid article identifier shows Not Found without API request');
  await page.goto(`${base}/account/cms/blog/articles/f0f0f0f0-0000-4000-8000-000000000099`);
  await expect(page.getByRole('alert')).toHaveText('Blog post not found.');
  checks.push('nonexistent valid article identifier preserves API Not Found');
  permissions = permissions.filter(permission => !permission.startsWith('cms.blog.articles:'));
  await page.goto(`${base}/account/cms/blog/articles`);
  await expect(page).toHaveURL(`${base}/account/profile`);
  checks.push('Pages permissions do not grant Articles route access');
  if (requests.some(request => /undefined|\/blog-(articles|posts)\/articles(?:$|\?)/.test(request.path))) throw new Error('Invalid identifier reached the API');
  if (errors.length) throw new Error(`Browser errors: ${errors.join('; ')}`);
  console.log(JSON.stringify({ checks, errors, requests: requests.length }));
} finally {
  await writeFile(`${root}/browser-results.json`, JSON.stringify({ base, mode: 'real browser, intercepted API fixtures; not live authenticated verification', checks, errors, requests }, null, 2));
  await browser.close();
}
