export function getDealById(id: string): Deal | undefined {
  return DEALS.find((d) => d.id === id);
}

export function getDealBySlug(slug: string): Deal | undefined {
  return DEALS.find((d) => d.slug === slug);
}

export function getDealsByCategory(categorySlug: string): Deal[] {
  return DEALS.filter((d) => d.categorySlug === categorySlug);
}

export function getFeaturedDeals(): Deal[] {
  return DEALS.filter((d) => d.isFeatured);
}

export function getHotDeals(): Deal[] {
  return DEALS.filter((d) => d.isHot);
}

export function searchDeals(query: string): Deal[] {
  const q = query.toLowerCase();
  return DEALS.filter(
    (d) =>
      d.title.toLowerCase().includes(q) ||
      d.providerName.toLowerCase().includes(q) ||
      d.description.toLowerCase().includes(q) ||
      d.categorySlug.includes(q),
  );
}
